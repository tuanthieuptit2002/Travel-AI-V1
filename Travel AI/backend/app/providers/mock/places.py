class MockPlacesProvider(PlacesProvider):
    """Curated, deterministic Vietnam place catalog for local development."""

    def __init__(self) -> None:
        self._places: Dict[str, PlaceDetails] = {place.id: place for place in _catalog()}

    def search_places(self, request: PlaceSearchRequest) -> List[PlaceSearchResult]:
        query_terms = request.query.casefold().split()
        destination = normalize_destination(request.destination) if request.destination else None
        results: List[PlaceSearchResult] = []
        for place in self._places.values():
            searchable = " ".join([place.name, place.description, place.destination] + place.tags).casefold()
            matches_query = not query_terms or all(term in searchable for term in query_terms)
            matches_destination = destination is None or normalize_destination(place.destination) == destination
            matches_category = request.category is None or place.category == request.category
            if matches_query and matches_destination and matches_category:
                results.append(
                    PlaceSearchResult(
                        **place.model_dump(exclude={"opening_hours", "price_level", "website"})
                    )
                )
        return results[: request.limit]

    def get_place_details(self, place_id: str) -> Optional[PlaceDetails]:
        return self._places.get(place_id)
